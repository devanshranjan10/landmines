# Build bench/LEADERBOARD.md from result files: bench/results/*.jsonl (the maintainers' runs) and
# bench/submissions/*/results.jsonl (anyone else's). Rows are (agent, model, setup) on one task split and condition;
# pass rate with a Wilson 95% interval. Sessions that never reached the model are not results and are dropped.
#   python3 scripts/bench/leaderboard.py
import collections, glob, json, math, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BENCH = os.path.join(ROOT, 'bench')
fresh = json.load(open(os.path.join(BENCH, 'split-fresh.json')))
y2024 = json.load(open(os.path.join(BENCH, 'split.json')))
SPLIT = {t: 'fresh-test' for t in fresh['test']} | {t: 'fresh-dev' for t in fresh['dev']} | {t: '2024-test' for t in y2024['test']} | {t: '2024-dev' for t in y2024['dev']}

ARM_NAMES = {
    'none': 'no help',
    'rules': 'landmine rules section',
    'hook': 'landmine hook (heuristic)',
    'cards': 'landmine hook (trigger cards)',
    'cards-warn': 'landmine hook (cards, context only)',
    'rules+cards': 'landmine rules + card hook',
    'rules-noisy': 'landmine rules, big-project index, usage ranking',
    'rules-noisy-conf': 'landmine rules, big-project index, confidence ranking',
    'web': 'web search on',
    'context7': 'Context7 MCP',
    'mcp': 'landmine MCP',
}


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def load():
    files = [(f, 'maintainers') for f in glob.glob(os.path.join(BENCH, 'results', '*.jsonl'))]
    files += [(f, os.path.basename(os.path.dirname(f))) for f in glob.glob(os.path.join(BENCH, 'submissions', '*', 'results.jsonl'))]
    rows = []
    for f, source in files:
        for line in open(f):
            if not line.strip():
                continue
            r = json.loads(line)
            if r.get('agentError') or 'error' in r or r.get('agent') == 'cmd' and str(r.get('label', '')).startswith('reference-'):
                continue
            r['_source'] = source
            r['_split'] = SPLIT.get(r['task'], '?')
            rows.append(r)
    return rows


MODEL_NAMES = {'sonnet': 'Claude Sonnet 5.5', 'haiku': 'Claude Haiku 5.5', 'opus': 'Claude Opus 5.5'}
# Simulations, not setups a user would run: shown in their own section, never ranked against real setups.
ABLATIONS = {'rules-noisy', 'rules-noisy-conf'}


def table(rows, split, condition, prompt, ablations=False):
    groups = collections.defaultdict(list)
    for r in rows:
        if r['_split'] != split or r.get('condition', 'exec') != condition or r.get('prompt', 'spec') != prompt:
            continue
        if (r['arm'] in ABLATIONS) != ablations:
            continue
        agent = r.get('label') or {'claude': 'Claude Code', 'codex': 'Codex CLI'}.get(r.get('agent', 'claude'), r.get('agent'))
        groups[(agent, MODEL_NAMES.get(r.get('model'), r.get('model')), r['arm'], r['_source'])].append(r)
    out = []
    for (agent, model, arm, source), v in groups.items():
        k = sum(1 for r in v if r['pass'])
        n = len(v)
        lo, hi = wilson(k, n)
        seeds = sorted({r['seed'] for r in v})
        out.append((k / n, agent, model, ARM_NAMES.get(arm, arm), k, n, lo, hi, len({r['task'] for r in v}), seeds, source))
    out.sort(key=lambda x: (-x[0], x[1], str(x[2]), x[3]))
    return out


def render(rows):
    lines = [
        '# landmine-bench leaderboard',
        '',
        'Generated by `python3 scripts/bench/leaderboard.py` from `bench/results/*.jsonl` and `bench/submissions/*/results.jsonl`. Do not edit by hand.',
        '',
        'Pass rate = runs whose final code passes the hidden test. Each run is one agent session on one task with one seed. 95% Wilson intervals. Rows with different seeds, dates or CLI versions are not paired; for head-to-head claims use `scripts/bench/paired.py` on runs from the same batch.',
        '',
    ]
    sections = [
        ('fresh-test', 'exec', 'terse', 'Headline: fresh-test (21 tasks, bugs filed after mid-2026), shell access, user-style prompts'),
        ('fresh-test', 'edit-only', 'terse', 'fresh-test, edit-only (no shell), user-style prompts'),
        ('fresh-test', 'exec', 'spec', 'fresh-test, shell access, fully specified prompts'),
        ('2024-test', 'exec', 'spec', '2024-test (18 tasks; contaminated control: models already know these bugs)'),
    ]
    for split, cond, prompt, title in sections:
        t = table(rows, split, cond, prompt)
        if not t:
            continue
        lines += [f'## {title}', '', '| # | Agent | Model | Setup | Passed | Rate | 95% CI | Tasks | Seeds | Source |', '|---|---|---|---|---|---|---|---|---|---|']
        for i, (rate, agent, model, arm, k, n, lo, hi, tasks, seeds, source) in enumerate(t, 1):
            seed_txt = f'{seeds[0]}–{seeds[-1]}' if len(seeds) > 1 else str(seeds[0])
            lines.append(f'| {i} | {agent} | {model} | {arm} | {k}/{n} | {rate:.0%} | {lo:.0%}–{hi:.0%} | {tasks} | {seed_txt} | {source} |')
        lines.append('')
    t = table(rows, 'fresh-test', 'exec', 'terse', ablations=True)
    if t:
        lines += ['## Ablation: the rules list in a big project (simulation, not ranked)', '', "Each task's index was mixed with a real 46-dependency project's 254 carded issues (D-43). Usage ranking is flattered here: the extra packages are not imported by the task project.", '', '| Setup | Passed | Rate | 95% CI | Seeds |', '|---|---|---|---|---|']
        for (rate, agent, model, arm, k, n, lo, hi, tasks, seeds, source) in t:
            lines.append(f'| {model}, {arm} | {k}/{n} | {rate:.0%} | {lo:.0%}–{hi:.0%} | {seeds[0]}–{seeds[-1]} |')
        lines.append('')
    lines += ['## Submitting', '', 'See `bench/README.md` § Submitting results.', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = render(load())
    open(os.path.join(BENCH, 'LEADERBOARD.md'), 'w').write(text)
    print(text[:3000])
